# -*- coding: utf-8 -*-
"""
field_aliases
-------------
Псевдонимы полей выходных слоёв.

Имена полей короткие и латинские, потому что по ним пишут выражения и фильтры.
Псевдоним это подпись столбца в таблице атрибутов и в форме объекта. Он стоит
на языке интерфейса и отвечает на вопрос, что в столбце лежит.

Псевдоним ставится слою после загрузки, а не полю в приёмнике. Псевдоним
на поле приёмника QGIS встречает предупреждением о несовместимости
с временными слоями, а свойство слоя в проекте временному слою не мешает.
"""

try:  # внутри плагина QGIS
    from .i18n import tr
except ImportError:  # headless-тесты
    from i18n import tr

__all__ = ["findings", "edits", "inserted_nodes", "coverage_nodes",
           "coverage_arcs", "borders"]


def findings():
    """Слой находок инструментов 1.01, 1.02, 1.07 и слой оставшихся проблем."""
    return {
        "num": tr("Номер"),
        "type": tr("Код нарушения"),
        "label": tr("Нарушение"),
        "severity": tr("Разряд"),
        "fid_a": tr("Объект"),
        "fid_b": tr("Второй объект"),
        "value": tr("Величина"),
        "note": tr("Пояснение"),
        "grp": tr("Группа"),
    }


def edits():
    """Слой точек правок инструмента 1.05."""
    return {
        "kind": tr("Вид правки"),
        "dist": tr("Смещение"),
        "ring": tr("Кольцо"),
    }


def inserted_nodes():
    """Слой вставленных узлов инструмента 1.06."""
    return {
        "kind": tr("Вид узла"),
        "dist": tr("Отклонение от ребра"),
    }


def coverage_nodes():
    """Слой узлов инструмента 2.03."""
    return {
        "node_id": tr("Номер узла"),
        "degree": tr("Степень"),
        "kind": tr("Вид узла"),
    }


def coverage_arcs():
    """Слой дуг инструмента 2.03."""
    return {
        "arc_id": tr("Номер дуги"),
        "from_node": tr("Узел начала"),
        "to_node": tr("Узел конца"),
        "left_fid": tr("Объект слева"),
        "right_fid": tr("Объект справа"),
        "length": tr("Длина"),
    }


def borders():
    """Слой границ инструмента 2.02."""
    return {
        "kind": tr("Код вида"),
        "label": tr("Вид границы"),
        "fid_a": tr("Объект с одной стороны"),
        "fid_b": tr("Объект с другой стороны"),
        "length": tr("Длина"),
        "val_a": tr("Значение с одной стороны"),
        "val_b": tr("Значение с другой стороны"),
    }
